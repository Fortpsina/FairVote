def t(key: str, locale: str = DEFAULT_LOCALE, **values: object) -> str:
    """Translate ``key``. Missing keys raise instead of silently printing the key."""
    catalogue = STRINGS.get(locale) or STRINGS[DEFAULT_LOCALE]
    try:
        template = catalogue[key]
    except KeyError as exc:  # pragma: no cover - guarded by a test
        raise KeyError(f"missing translation key: {key}") from exc
    return template.format(**values) if values else template


def keys() -> set[str]:
    return set(STRINGS[DEFAULT_LOCALE])


def available_locales() -> list[str]:
    return sorted(STRINGS)
